#!/usr/bin/env python3
"""Reproducible native size/correctness evaluation (see paper/README.md).

Requires a built plugin and matching LLVM tools; uses only the Python standard
library. Retains commands, IR and binaries beside the JSON and generated tables.
Code size is not interpreted as resistance to reverse engineering.
"""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import statistics
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
BENCH = Path(__file__).resolve().parent
FUNCTIONS = ("eval_verify_score", "eval_verify_item", "eval_check_movement",
             "eval_validate_token")
# Registry order; these are NOT the shipping BALANCED / STRONG profiles.
CONFIGS = {
    "plain": [],
    "core": ["str", "fla", "bcf", "sub", "co"],
    "extended": ["str", "fla", "bcf", "sub", "co", "ibr", "bbr", "bbs", "mvo"],
}


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def measure(objdump, binary, run):
    sections = run([objdump, "--section-headers", binary])
    matches = re.findall(r"^\s*\d+\s+(?:__text|\.text)\s+([0-9a-fA-F]+)\b",
                         sections, re.MULTILINE)
    if len(matches) != 1:
        raise ValueError(f"Expected one text section in {binary}")
    disasm = run([objdump, "--disassemble", "--no-show-raw-insn", binary])
    counts, current = {}, None
    for line in disasm.splitlines():
        label = re.match(r"^\s*[0-9a-fA-F]+ <([^>]+)>:$", line)
        if label:
            current = label[1].removeprefix("_")
            counts.setdefault(current, 0)
        elif current and re.match(r"^\s*[0-9a-fA-F]+:\s+\S", line):
            counts[current] += 1
    missing = [name for name in FUNCTIONS if not counts.get(name)]
    if missing:
        raise ValueError(f"Missing benchmark symbols: {missing}")
    return {"file_bytes": binary.stat().st_size,
            "text_bytes": int(matches[0], 16),
            "function_instructions": {name: counts[name] for name in FUNCTIONS},
            "target_instructions": sum(counts[name] for name in FUNCTIONS)}


def write_tables(data, output):
    rows = data["runs"]
    baseline = next(row for row in rows if row["config"] == "plain")
    lines = [
        "% Generated by run_eval.py; do not edit.",
        r"\newcommand{\EvalLLVM}{" + data["llvm_version"] + "}",
        r"\newcommand{\EvalSeeds}{" + ", ".join(map(str, data["seeds"])) + "}",
        r"\begin{table}[t]", r"\centering\footnotesize",
        r"\caption{Native measurements. Ranges span three fixed seeds.",
        r"Instructions cover T1--T4; text includes the unchanged harness.}",
        r"\label{tab:overhead}", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"Config. & Text (B) & Text ratio & Instructions & Instr. ratio \\",
        r"\midrule",
    ]

    def span(values, digits=0):
        lo, hi = min(values), max(values)
        fmt = (lambda n: f"{n:.{digits}f}") if digits else (lambda n: f"{n:,}")
        return fmt(lo) if lo == hi else fmt(lo) + "--" + fmt(hi)

    for config in CONFIGS:
        group = [row for row in rows if row["config"] == config]
        sizes = [r["text_bytes"] for r in group]
        instr = [r["target_instructions"] for r in group]
        lines.append(f"{config.title()} & {span(sizes)} & "
                     f"{span([n / baseline['text_bytes'] for n in sizes], 2)} & "
                     f"{span(instr)} & "
                     f"{span([n / baseline['target_instructions'] for n in instr], 2)} "
                     + r"\\")
    lines += [
        r"\bottomrule", r"\end{tabular}", r"\end{table}",
        r"\begin{table}[t]", r"\centering\footnotesize",
        r"\caption{Per-function machine instructions: median [min, max]",
        r"across seeds. Plain is compiled once.}", r"\label{tab:perfunc}",
        r"\begin{tabular}{lrrr}", r"\toprule",
        r"Function & Plain & Core & Extended \\", r"\midrule",
    ]
    for index, name in enumerate(FUNCTIONS, 1):
        cells = []
        for config in CONFIGS:
            values = [r["function_instructions"][name] for r in rows
                      if r["config"] == config]
            cells.append(str(values[0]) if len(values) == 1 else
                         f"{statistics.median(values):.0f} [{min(values)}, {max(values)}]")
        lines.append(f"T{index} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (output / "native_tables.tex").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llvm-prefix", type=Path, default=os.environ.get("LLVM_PREFIX"))
    parser.add_argument("--plugin", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "paper/results/native")
    parser.add_argument("--seeds", type=int, nargs=3, default=[1, 42, 12345])
    args = parser.parse_args()
    if not args.llvm_prefix:
        parser.error("set --llvm-prefix or LLVM_PREFIX to the plugin's LLVM installation")
    if len(set(args.seeds)) != 3 or any(s <= 0 or s >= 2**64 for s in args.seeds):
        parser.error("provide three distinct nonzero uint64 seeds")
    plugin = args.plugin.resolve(strict=True)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    # Invalidate old reports before a fresh run, so failure cannot look successful.
    for name in ("native_eval.json", "native_tables.tex"):
        (output / name).unlink(missing_ok=True)
    commands = []

    def run(argv):
        argv = list(map(str, argv))
        result = subprocess.run(argv, cwd=ROOT, text=True, capture_output=True, timeout=120)
        commands.append({"argv": argv, "returncode": result.returncode,
                         "stdout": result.stdout, "stderr": result.stderr})
        (output / "commands.json").write_text(json.dumps(commands, indent=2) + "\n")
        if result.returncode:
            raise RuntimeError(f"Command failed: {argv}\n{result.stderr}")
        return result.stdout

    tool = {name: args.llvm_prefix.resolve() / "bin" / name
            for name in ("clang", "opt", "llc", "llvm-objdump")}
    versions = {name: run([path, "--version"]).strip() for name, path in tool.items()}
    llvm_versions = [re.search(r"version (\d+\.\d+\.\d+)", v)[1] for v in versions.values()]
    if len(set(llvm_versions)) != 1:
        raise ValueError("clang, opt, llc and llvm-objdump versions must match")
    source, harness = BENCH / "eval_functions.c", BENCH / "eval_main.c"
    raw, harness_obj = output / "input.bc", output / "harness.o"
    # O1 frontend attributes, but defer the IR optimizer to opt.
    run([tool["clang"], "-O1", "-Xclang", "-disable-llvm-passes", "-emit-llvm",
         "-c", source, "-o", raw])
    run([tool["clang"], "-O1", "-c", harness, "-o", harness_obj])
    data = {
        "schema_version": 1, "measured_at_utc": datetime.now(timezone.utc).isoformat(),
        "revision": run(["git", "rev-parse", "HEAD"]).strip(),
        "worktree_status": run(["git", "status", "--short"]).strip(),
        "host": platform.platform(), "machine": platform.machine(),
        "target": run([tool["clang"], "-dumpmachine"]).strip(),
        "llvm_version": llvm_versions[0], "tool_versions": versions,
        "plugin_sha256": sha256(plugin),
        "source_sha256": {str(p.relative_to(ROOT)): sha256(p)
                          for p in (source, harness, Path(__file__).resolve(),
                                    ROOT / "include/kagura/PassRegistry.def")},
        "seeds": args.seeds, "configurations": CONFIGS,
        "tuning": {"bcf_prob": 30, "bcf_iter": 1, "sub_iter": 1,
                   "bbs_min": 3, "bbs_max_splits": 2},
        "pipeline": "clang O1 frontend; opt default<O1> with OptimizerLast plugin; llc -O=1; clang link",
        "measurement_scope": {
            "text_bytes": "linked executable text section including harness",
            "target_instructions": "sum of T1-T4 disassembled machine instructions"},
        "runs": [],
    }
    for config, passes in CONFIGS.items():
        for seed in ([None] if config == "plain" else args.seeds):
            stem = output / f"{config}_{seed if seed is not None else 'baseline'}"
            ir = stem.with_suffix(".ll")
            flags = [] if seed is None else [
                f"-load-pass-plugin={plugin}", f"-kagura-seed={seed}",
                "-kagura-bcf-prob=30", "-kagura-bcf-iter=1", "-kagura-sub-iter=1",
                "-kagura-bbs-min=3", "-kagura-bbs-max-splits=2",
                *[f"-kagura-{p}" for p in passes]]
            run([tool["opt"], *flags, "-passes=default<O1>", "-verify-each", raw,
                 "-S", "-o", ir])
            if seed is not None:
                repeat = stem.with_suffix(".repeat.ll")
                run([tool["opt"], *flags, "-passes=default<O1>", "-verify-each", raw,
                     "-S", "-o", repeat])
                if ir.read_bytes() != repeat.read_bytes():
                    raise ValueError(f"IR reproducibility failed: {config}, seed {seed}")
            obj = stem.with_suffix(".o")
            run([tool["llc"], "-O=1", "-filetype=obj", "-relocation-model=pic",
                 ir, "-o", obj])
            run([tool["clang"], harness_obj, obj, "-o", stem])
            correctness = run([stem]).strip()
            if correctness != "Self-test: 7/7 passed":
                raise ValueError(f"Unexpected correctness output: {correctness}")
            row = {"config": config, "seed": seed, "correctness": correctness,
                   "ir_repeat_identical": None if seed is None else True,
                   "ir_sha256": sha256(ir), "binary_sha256": sha256(stem),
                   **measure(tool["llvm-objdump"], stem, run)}
            data["runs"].append(row)
            print(f"{config:8} seed={str(seed):5} text={row['text_bytes']:5} B "
                  f"target instructions={row['target_instructions']:4}; {correctness}",
                  flush=True)
    (output / "native_eval.json").write_text(json.dumps(data, indent=2) + "\n")
    write_tables(data, output)
    print(f"Results: {output}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired) as exc:
        print(f"Evaluation failed: {exc}", file=sys.stderr)
        sys.exit(1)
