#!/usr/bin/env python3
"""Regenerate the profile size/outcome table from a completed evaluation."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def span(values, decimals=None):
    low, high = min(values), max(values)

    def fmt(n):
        return (f"{n:.{decimals}f}" if decimals is not None else
                f"{n:,}".replace(",", "{,}"))

    return fmt(low) if low == high else fmt(low) + "--" + fmt(high)


def render_table(data):
    # Version 1 is the completed historical record shipped with the paper.
    # Version 2 records explicit running/failed/complete lifecycle states.
    status = data.get("status", "complete" if data.get("schema_version") == 1 else None)
    if status != "complete":
        raise ValueError(f"Cannot render an incomplete evaluation (status={status!r})")
    seeds = data["method"]["seeds"]
    if (not seeds or any(type(seed) is not int or not 0 < seed < 2**64 for seed in seeds)
            or len(set(seeds)) != len(seeds)):
        raise ValueError("Expected distinct nonzero uint64 seeds in the result")
    seed_text = str(seeds[0]) if len(seeds) == 1 else (
        ", ".join(map(str, seeds[:-1])) + ", and " + str(seeds[-1])
        if len(seeds) > 2 else " and ".join(map(str, seeds)))
    architecture = data["host"]["architecture"]
    if architecture not in ("arm64", "x86_64"):
        raise ValueError(f"Unsupported native macOS architecture: {architecture!r}")
    architecture = architecture.replace("_", r"\_")
    rows = data["observations"]
    configurations = [("plain", False)] + [(name, ablate) for ablate in (False, True)
                                           for name in ("FAST", "BALANCED", "STRONG")]
    groups = {}
    for name, ablate in configurations:
        group = [row for row in rows if row["profile"] == name
                 and row["anti_debug_disabled"] == ablate]
        expected = [None] if name == "plain" else seeds
        if len(group) != len(expected) or {row["seed"] for row in group} != set(expected):
            raise ValueError(f"Missing or duplicate observations for {name}, ablated={ablate}")
        groups[name, ablate] = group
    if len(rows) != 1 + 6 * len(seeds):
        raise ValueError("Unexpected observations outside the evaluated configurations")
    base = groups["plain", False][0]
    if not (base["selftest_passed"] and base["differential_passed"]):
        raise ValueError("Cannot render a comparison against a failed baseline")
    return_count = data["method"]["differential_inputs_per_function"] * data["method"]["functions"]
    count_text = f"{return_count:,}"
    lines = [r"% Generated by paper/render_results.py from the selected evaluation JSON.",
             r"\begin{table*}[t]", r"\centering\footnotesize",
             (r"\caption{Profile observations on " + architecture + " macOS. "
              + ("Seed: " if len(seeds) == 1 else "Ranges span seeds ")
              + seed_text + "; plain is built once. "
              + r"A superscript $^{-}$ disables only anti-debug instrumentation. "
              + "Sizes are bytes; executable sizes use the seven-case self-test driver. "
              + "Completed runs pass both that driver and the " + count_text
              + "-value differential comparison.}"),
             r"\label{tab:current-results}",
             r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
             r"Configuration & Execution outcome & Subject text & Text ratio & Executable text & File size & Completed \\",
             r"\midrule"]
    for name, ablate in configurations:
        group = groups[name, ablate]
        passed = sum(row["selftest_passed"] and row["differential_passed"] for row in group)
        if passed == len(group):
            outcome = "Matches baseline"
        elif all(row["selftest_execution"]["returncode"] == -6 and
                 row["differential_execution"]["returncode"] == -6 for row in group):
            outcome = "Startup abort"
        else:
            outcome = "Mixed/failing runs"
        label = ("Plain" if name == "plain" else name) + (r"$^{-}$" if ablate else "")
        cells = [label, outcome, span([row["subject_text_bytes"] for row in group]),
                 "$" + span([row["subject_text_bytes"] / base["subject_text_bytes"]
                              for row in group], 2).replace("--", r"\text{--}") + r"\times$",
                 span([row["executable_text_bytes"] for row in group]),
                 span([row["executable_bytes"] for row in group]), f"{passed}/{len(group)}"]
        lines.append(" & ".join(cells) + r" \\")
        if name == "STRONG" and not ablate:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=HERE / "results/current_eval.json")
    parser.add_argument("--output", type=Path, default=HERE / "results/current_table.tex")
    args = parser.parse_args()
    if args.input.resolve() == args.output.resolve():
        parser.error("input JSON and output table must be different files")
    # A failed render must not leave a stale table available to LaTeX.
    args.output.unlink(missing_ok=True)
    table = render_table(json.loads(args.input.read_text()))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(table)


if __name__ == "__main__":
    main()
